#!/usr/bin/env python3
"""Generate test/fixtures/PricingReference.sol from DeepBook Predict's pricing_reference_data.move.

The Move file is Mysten's independent true-math reference (Python stdlib erf/log/sqrt over real
on-chain Block Scholes SVI rows). Re-emitting it verbatim lets the Solidity port be checked against
the same points and the same per-point tolerances the Sui pricer is held to.

usage: gen_pricing_reference.py <path/to/pricing_reference_data.move> <out.sol>
"""
import re, sys

src = open(sys.argv[1]).read()
U64_MAX = (1 << 64) - 1

def num(tok):
    tok = tok.strip()
    if tok == "constants::pos_inf!()": return U64_MAX
    if tok == "constants::neg_inf!()": return 0
    return int(tok.replace("_", ""))

def scenario_fn(name, cast):
    body = re.search(r"public fun %s\(s: u64\): \w+ \{(.*?)\n\}" % name, src, re.S).group(1)
    vals = re.findall(r"s == (\d)\) \{\s*([\w_]+)\s*\}", body)
    out = {int(k): cast(v) for k, v in vals}
    assert sorted(out) == [0, 1, 2, 3], (name, out)
    return out

ints = lambda v: int(v.replace("_", ""))
bools = lambda v: v == "true"
fields = {
    "spot": scenario_fn("spot", ints), "forward": scenario_fn("forward", ints),
    "a": scenario_fn("svi_a", ints), "b": scenario_fn("svi_b", ints),
    "sigma": scenario_fn("svi_sigma", ints),
    "rhoMag": scenario_fn("svi_rho_magnitude", ints), "rhoNeg": scenario_fn("svi_rho_is_negative", bools),
    "mMag": scenario_fn("svi_m_magnitude", ints), "mNeg": scenario_fn("svi_m_is_negative", bools),
}

body = re.search(r"public fun points\(s: u64\): vector<RefPoint> \{(.*?)\n\}", src, re.S).group(1)
blocks = re.split(r"(?:if|else if) \(s == (\d)\) \{", body)
points = {}
for i in range(1, len(blocks), 2):
    s = int(blocks[i])
    pts = re.findall(r"pt\(([^,]+),\s*([^,]+),\s*([^,]+),\s*([^)]+)\)", blocks[i + 1])
    points[s] = [tuple(num(x) for x in p) for p in pts]
assert sorted(points) == [0, 1, 2, 3]
total = sum(len(v) for v in points.values())

L = []
L.append("// SPDX-License-Identifier: Apache-2.0")
L.append("// @generated by script/gen/gen_pricing_reference.py from DeepBook Predict")
L.append("// packages/predict/tests/pricing/pricing_reference_data.move. DO NOT EDIT BY HAND.")
L.append("pragma solidity 0.8.28;\n")
L.append("library PricingReference {")
L.append("    struct Scenario { uint256 spot; uint256 forward; uint256 a; uint256 b; uint256 sigma;")
L.append("        uint256 rhoMag; bool rhoNeg; uint256 mMag; bool mNeg; }")
L.append("    struct Point { uint256 lower; uint256 higher; uint256 reference_; uint256 tolerance; }\n")
L.append("    uint256 internal constant SCENARIOS = 4;")
L.append("    uint256 internal constant TOTAL_POINTS = %d;\n" % total)
L.append("    function scenario(uint256 s) internal pure returns (Scenario memory) {")
for s in range(4):
    f = {k: v[s] for k, v in fields.items()}
    L.append("        if (s == %d) return Scenario(%d, %d, %d, %d, %d, %d, %s, %d, %s);" % (
        s, f["spot"], f["forward"], f["a"], f["b"], f["sigma"], f["rhoMag"],
        str(f["rhoNeg"]).lower(), f["mMag"], str(f["mNeg"]).lower()))
L.append('        revert("no scenario");')
L.append("    }\n")
L.append("    function points(uint256 s) internal pure returns (Point[] memory p) {")
for s in range(4):
    L.append("        if (s == %d) {" % s)
    L.append("            p = new Point[](%d);" % len(points[s]))
    for i, (lo, hi, ref, tol) in enumerate(points[s]):
        L.append("            p[%d] = Point(%d, %d, %d, %d);" % (i, lo, hi, ref, tol))
    L.append("            return p;")
    L.append("        }")
L.append('        revert("no scenario");')
L.append("    }")
L.append("}")
open(sys.argv[2], "w").write("\n".join(L) + "\n")
print(f"wrote {sys.argv[2]}: {total} points across 4 scenarios")
